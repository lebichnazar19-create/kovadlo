"""
Орієнтовні довідкові величини для модуля 12 (механіка та фізика руху):
прискорення вільного падіння, модуль Юнга типових конструкційних
матеріалів, коефіцієнт запасу міцності, гранична відносна прогинистість
балки.

**УВАГА:** усі значення нижче — орієнтовні, з поширених довідників опору
матеріалів і загальної інженерної практики, а НЕ дослівна виписка з
чинного стандарту. Перед реальним застосуванням звірте з сертифікатом
на конкретну партію матеріалу й чинними нормами проєктування
(наприклад, EN 1993-1-1 для сталевих конструкцій).
"""

from __future__ import annotations

GRAVITY_M_S2 = 9.81
"""Прискорення вільного падіння, м/с² (стандартне значення, фізика)."""


ELASTIC_MODULUS_MPA: dict[str, float] = {
    # Ключ — точна назва матеріалу з бази модуля 7 (material_seed.py):
    # так само, як MaterialSpec.name зв'язує стіну/провід з базою,
    # тут ім'я зв'язує матеріал балки з модулем Юнга (по імені, без
    # додавання нового поля в MaterialSpec/Material — ядро незмінне).
    "Сталь конструкційна S235JR": 210_000.0,
    "Сталь нержавіюча AISI 304 (1.4301)": 193_000.0,
    "Алюміній (сплав 6060, Т6)": 69_000.0,
    "Мідь (метал, Cu-ETP)": 117_000.0,
    "Латунь (CuZn37)": 100_000.0,
}
"""Модуль пружності (Юнга), МПа — типові значення для металів бази
модуля 7, довідник опору матеріалів, орієнтовно."""


DEFAULT_SAFETY_FACTOR = 1.5
"""Типовий коефіцієнт запасу міцності для статичних конструкцій —
орієнтовне інженерне значення (спрощення часткових коефіцієнтів
EN 1993), не заміняє повний нормативний розрахунок."""


MAX_DEFLECTION_RATIO = 1.0 / 250.0
"""Гранично допустиме відношення прогину до прольоту балки, L/250 —
типова експлуатаційна межа для будівельних балок (орієнтовно, за
загальною практикою, близько до підходу EN 1993-1-1 додатку A)."""


def elastic_modulus_mpa_for(material_name: str) -> float | None:
    """Модуль Юнга за назвою матеріалу з бази модуля 7, якщо є в
    таблиці вище; інакше `None` (виклик має явно передати значення)."""
    return ELASTIC_MODULUS_MPA.get(material_name)
