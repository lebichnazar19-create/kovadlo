"""
Нормативні дані для розрахунку теплового балансу приміщення.

Розрахункові зовнішні температури — орієнтовні значення за кліматичними
зонами Польщі (структура на кшталт національного додатку до **PN-EN
12831** "Розрахунок розрахункового теплового навантаження"). Реальне
розрахункове значення для конкретної локації треба брати з чинної карти
кліматичного районування, а не з цієї спрощеної таблиці.
"""

from __future__ import annotations

from enum import Enum


class ClimateZone(Enum):
    """Кліматична зона Польщі (I — найтепліша, V — найхолодніша)."""

    ZONE_I = "I"
    ZONE_II = "II"
    ZONE_III = "III"
    ZONE_IV = "IV"
    ZONE_V = "V"


# Орієнтовна розрахункова зовнішня температура за зоною, °C (PN-EN 12831,
# національний додаток — спрощено, лише для орієнтовного розрахунку).
DESIGN_OUTDOOR_TEMP_C: dict[ClimateZone, float] = {
    ClimateZone.ZONE_I: -16.0,
    ClimateZone.ZONE_II: -18.0,
    ClimateZone.ZONE_III: -20.0,
    ClimateZone.ZONE_IV: -22.0,
    ClimateZone.ZONE_V: -24.0,
}

# Розрахункова внутрішня температура за замовчуванням, °C (типова для
# житлових приміщень).
DEFAULT_INDOOR_TEMP_C = 20.0

# Об'ємна теплоємність повітря, Вт·год/(м³·К) — орієнтовно, для
# розрахунку тепловтрат на вентиляцію Q = c · V̇ · ΔT.
AIR_VOLUMETRIC_HEAT_CAPACITY_WH_M3K = 0.34

# Орієнтовний ряд потужностей радіаторів, Вт (типові каталожні кроки).
