"""
Нормативні дані для розрахунку вентиляції.

Орієнтовні значення поширеної інженерної практики (національні додатки
на кшталт PN-B-03430 для житлових будівель у Польщі, загальні
рекомендації EN 16798-1 щодо повітрообміну) — НЕ дослівна виписка з
чинної норми. Мінімальна витрата витяжки для "мокрих" приміщень і
кратність повітрообміну для решти приміщень — типові орієнтири для
попереднього розрахунку; для реального проєкту звіряйтеся з чинною
редакцією норми й вимогами вентиляційної системи будівлі.
"""

from __future__ import annotations

from enum import Enum


class VentilatedRoomKind(Enum):
    """Тип приміщення для розрахунку повітрообміну."""

    KITCHEN = "кухня"
    BATHROOM = "ванна"
    TOILET = "туалет"
    BEDROOM = "спальня"
    LIVING_ROOM = "вітальня"


# Мінімальна витрата витяжного повітря для "мокрих" приміщень, м³/год
# (фіксована незалежно від об'єму — типова практика для житла).
MINIMUM_EXHAUST_M3_H: dict[VentilatedRoomKind, float] = {
    VentilatedRoomKind.KITCHEN: 50.0,
    VentilatedRoomKind.BATHROOM: 50.0,
    VentilatedRoomKind.TOILET: 30.0,
}

# Кратність повітрообміну для решти приміщень, 1/год (обсяг приміщення ×
# кратність = потрібна витрата, м³/год).
AIR_CHANGES_PER_HOUR: dict[VentilatedRoomKind, float] = {
    VentilatedRoomKind.BEDROOM: 0.5,
    VentilatedRoomKind.LIVING_ROOM: 0.5,
}

# Густина повітря, кг/м³ (за нормальних кімнатних умов, орієнтовно).
AIR_DENSITY_KG_M3 = 1.2

# Рекомендована максимальна швидкість повітря в каналі житлової будівлі,
# м/с — вище зростає шум; орієнтовна практична межа.
MAX_RECOMMENDED_VELOCITY_M_S = 4.0

# Орієнтовний коефіцієнт тертя (безрозмірний, формула Дарсі-Вейсбаха)
# для гладких пластикових/оцинкованих повітроводів.
DEFAULT_FRICTION_FACTOR = 0.02

# Стандартний ряд діаметрів круглих повітроводів, мм.
STANDARD_ROUND_DUCT_DIAMETERS_MM: list[float] = [80, 100, 125, 150, 160, 200, 250, 315]

# Орієнтовний каталог витяжних вентиляторів: (макс. витрата м³/год,
# макс. корисний тиск Па, назва) — типові побутові класи потужності.
STANDARD_FANS: list[tuple[float, float, str]] = [
    (30.0, 50.0, "Побутовий вентилятор, базовий клас"),
    (60.0, 80.0, "Побутовий вентилятор, посилений клас"),
    (100.0, 120.0, "Канальний вентилятор, малий"),
    (200.0, 150.0, "Канальний вентилятор, середній"),
    (350.0, 200.0, "Канальний вентилятор, великий"),
]
