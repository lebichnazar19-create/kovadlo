"""
Нормативні рівні освітленості за призначенням приміщення.

Норма: **EN 12464-1** ("Освітлення робочих місць. Частина 1: робочі
місця у приміщеннях"). Реальний стандарт задає рівні освітленості для
конкретних ЗАВДАНЬ (напр. окремо "робоча поверхня кухні" і "загальне
освітлення кухні", десятки позицій для офісів/майстерень тощо).

**УВАГА:** значення нижче — по ОДНОМУ орієнтовному узагальненому рівню
на тип приміщення (спрощення для побутового проєктування), а НЕ повна
таблиця норми з усіма робочими завданнями. Для нежитлових/виробничих
приміщень і складних завдань зору звіряйтеся з повним текстом EN 12464-1.
"""

from __future__ import annotations

from enum import Enum


class RoomPurpose(Enum):
    """Призначення приміщення для підбору освітлення."""

    KITCHEN = "кухня"
    BATHROOM = "ванна"
    BEDROOM = "спальня"
    LIVING_ROOM = "вітальня"
    WORKSHOP = "майстерня"
    OFFICE = "офіс/кабінет"
    HALLWAY = "коридор"
    STAIRS = "сходи"


# Орієнтовний рекомендований рівень освітленості, лк (EN 12464-1,
# узагальнено по приміщенню — див. застереження в docstring модуля).
RECOMMENDED_LUX: dict[RoomPurpose, float] = {
    RoomPurpose.KITCHEN: 300.0,
    RoomPurpose.BATHROOM: 200.0,
    RoomPurpose.BEDROOM: 150.0,
    RoomPurpose.LIVING_ROOM: 150.0,
    RoomPurpose.WORKSHOP: 300.0,
    RoomPurpose.OFFICE: 500.0,
    RoomPurpose.HALLWAY: 100.0,
    RoomPurpose.STAIRS: 100.0,
}

# Типові орієнтовні межі коефіцієнта використання світлового потоку (utilization
# factor) і коефіцієнта запасу (maintenance factor) для побутових приміщень
# зі світлими поверхнями — реальне значення залежить від фотометрії
# конкретного світильника й індексу приміщення, тут — розумні значення
# за замовчуванням для орієнтовного розрахунку.
DEFAULT_UTILIZATION_FACTOR = 0.5
DEFAULT_MAINTENANCE_FACTOR = 0.8
