"""
Нормативні дані та формули для розрахунку електропроводки.

Норма: PN-HD 60364 (польська національна редакція гармонізованої серії
IEC 60364, "Електричні установки низької напруги"). Використана тут
методика відповідає структурі таких частин норми:

- **PN-HD 60364-4-41** "Захист від ураження електричним струмом" —
  підстава вимоги про пристрій захисного відключення (ПЗВ/дифавтомат)
  для кіл розеток і вологих приміщень — див. `rcd_required_for_kinds`.
- **PN-HD 60364-4-43** "Захист від надструмів" — правило координації
  Ib ≤ In ≤ Iz (розрахунковий струм ≤ номінал апарата захисту ≤
  струмонесуча здатність провідника) — реалізують `select_breaker_rating_a`
  (умова Ib ≤ In) і `select_cross_section_mm2` (умова In ≤ Iz).
- **PN-HD 60364-5-52** "Вибір і монтаж електроустаткування. Електропроводки" —
  підстава таблиць струмонесучої здатності провідників (`AMPACITY_A`) і
  додатку щодо допустимого падіння напруги (типово рекомендують 3-5% від
  точки приєднання до найвіддаленішої точки кола залежно від призначення;
  тут за умовою задачі використана єдина межа 3% для всіх кіл —
  `MAX_VOLTAGE_DROP_PERCENT_DEFAULT`).

**УВАГА — важливе застереження:** конкретні числові значення в таблицях
нижче (струмонесуча здатність, стандартний ряд перерізів, номінали
автоматів) — це типові, орієнтовні інженерні значення для ілюстрації
методики розрахунку, а НЕ дослівна виписка з чинного тексту норми (яка
залежить ще й від способу прокладання, температури середовища, кількості
кіл поруч тощо). Перед реальним монтажем ці значення ОБОВ'ЯЗКОВО треба
звірити з чинною редакцією PN-HD 60364 і доручити розрахунок
кваліфікованому електрику/проектувальнику.
"""

from __future__ import annotations

import math
from enum import Enum

from .electrical_point import PointKind


class PhaseType(Enum):
    """Тип живлення кола/групи."""

    SINGLE = "однофазна"
    THREE = "трифазна"


# Номінальна напруга, В. Для трифазної — лінійна (міжфазна) напруга.
VOLTAGE_V: dict[PhaseType, float] = {
    PhaseType.SINGLE: 230.0,
    PhaseType.THREE: 400.0,
}

# Питомий опір мідного провідника при робочій температурі жили, Ом·мм²/м.
# Дещо вище за "холодний" опір міді при 20°C (0.0178), щоб закласти запас
# на нагрів жили під тривалим навантаженням — типовий підхід у практичних
# методиках перевірки падіння напруги за PN-HD 60364-5-52.
COPPER_RESISTIVITY_OHM_MM2_PER_M = 0.0225

# Максимально допустиме падіння напруги, % — за умовою задачі єдине для
# всіх кіл (норма дозволяє диференціювати за призначенням кола, тут це
# спрощено до однієї межі).
MAX_VOLTAGE_DROP_PERCENT_DEFAULT = 3.0

# Стандартний ряд перерізів мідних жил, мм² (типовий ряд для побутової
# силової проводки; менші за 1.5 мм² для силових кіл не використовуються).
STANDARD_CROSS_SECTIONS_MM2: list[float] = [1.5, 2.5, 4.0, 6.0, 10.0, 16.0, 25.0]

# Орієнтовна тривало допустима струмонесуча здатність мідних жил з ПВХ-
# ізоляцією, А (спрощено для типового способу прокладки в помешканні —
# кабель у трубі в стіні). Ілюстративні значення — див. застереження
# в docstring модуля вище.
AMPACITY_A: dict[float, float] = {
    1.5: 17.5,
    2.5: 24.0,
    4.0: 32.0,
    6.0: 41.0,
    10.0: 57.0,
    16.0: 76.0,
    25.0: 96.0,
}

# Стандартний ряд номіналів автоматичних вимикачів, А (характеристика
# ряду за IEC 60898).
STANDARD_BREAKER_RATINGS_A: list[float] = [6, 10, 16, 20, 25, 32, 40, 50, 63, 80, 100]

# Мінімальний переріз за призначенням кола — поширена інженерна практика
# (а не буквальний текст норми): освітлення — 1.5 мм², силові кола з
# розетками — 2.5 мм². Це значення за замовчуванням у `Group`, його завжди
# можна підвищити для конкретної групи (наприклад, для плити чи бойлера).
MIN_CROSS_SECTION_LIGHTING_MM2 = 1.5
MIN_CROSS_SECTION_POWER_MM2 = 2.5


def calculate_current_a(power_w: float, phase: PhaseType, power_factor: float = 1.0) -> float:
    """Розрахунковий струм кола, А.

    Однофазна мережа 230 В: I = P / (U × cosφ).
    Трифазна мережа 400 В (лінійна напруга, симетричне навантаження):
    I = P / (√3 × U × cosφ).
    """
    if power_factor <= 0:
        raise ValueError("Коефіцієнт потужності має бути додатним")
    if phase is PhaseType.SINGLE:
        return power_w / (VOLTAGE_V[PhaseType.SINGLE] * power_factor)
    return power_w / (math.sqrt(3) * VOLTAGE_V[PhaseType.THREE] * power_factor)


def voltage_drop_percent(cross_section_mm2: float, current_a: float, length_m: float, phase: PhaseType) -> float:
    """Падіння напруги, % від номінальної напруги фази/лінії.

    `length_m` — довжина траси в один кінець (від щитка до точки);
    формула сама враховує подвійний (туди-назад) шлях струму для
    однофазного кола:

      однофазна:  ΔU = (2 · L · I · ρ) / S
      трифазна:   ΔU = (√3 · L · I · ρ) / S
    """
    if cross_section_mm2 <= 0:
        raise ValueError("Переріз жили має бути додатним")
    if phase is PhaseType.SINGLE:
        drop_v = (2 * length_m * current_a * COPPER_RESISTIVITY_OHM_MM2_PER_M) / cross_section_mm2
        return drop_v / VOLTAGE_V[PhaseType.SINGLE] * 100.0
    drop_v = (math.sqrt(3) * length_m * current_a * COPPER_RESISTIVITY_OHM_MM2_PER_M) / cross_section_mm2
    return drop_v / VOLTAGE_V[PhaseType.THREE] * 100.0


def select_breaker_rating_a(design_current_a: float) -> float:
    """Найменший стандартний номінал автомата In ≥ Ib.

    PN-HD 60364-4-43, перша умова координації захисту: Ib ≤ In.
    """
    for rating in STANDARD_BREAKER_RATINGS_A:
        if rating >= design_current_a:
            return rating
    raise ValueError(
        f"Розрахунковий струм {design_current_a:.1f} А перевищує найбільший "
        f"номінал автомата в таблиці ({STANDARD_BREAKER_RATINGS_A[-1]:.0f} А) — "
        "групу потрібно розділити на кілька кіл"
    )


def select_cross_section_mm2(
    design_current_a: float,
    breaker_rating_a: float,
    length_m: float,
    phase: PhaseType,
    *,
    min_cross_section_mm2: float = MIN_CROSS_SECTION_LIGHTING_MM2,
    max_voltage_drop_percent: float = MAX_VOLTAGE_DROP_PERCENT_DEFAULT,
) -> float:
    """Найменший стандартний переріз, що одночасно задовольняє:

    - PN-HD 60364-4-43: Iz ≥ In (струмонесуча здатність жили не менша за
      номінал апарата захисту — друга умова координації In ≤ Iz);
    - PN-HD 60364-5-52 (додаток щодо падіння напруги): падіння напруги на
      розрахунковому струмі не перевищує `max_voltage_drop_percent`.
    """
    candidates = [
        s for s in STANDARD_CROSS_SECTIONS_MM2 if s >= min_cross_section_mm2 and AMPACITY_A[s] >= breaker_rating_a
    ]
    for section in candidates:
        drop = voltage_drop_percent(section, design_current_a, length_m, phase)
        if drop <= max_voltage_drop_percent:
            return section
    raise ValueError(
        "Жоден стандартний переріз зі списку не задовольняє одночасно "
        f"струмове навантаження ({breaker_rating_a:.0f} А) і допустиме падіння "
        f"напруги ({max_voltage_drop_percent:.0f}%) на довжині {length_m:.1f} м — "
        "траса задовга для цього навантаження: потрібен більший переріз "
        "(поза стандартним рядом) або коротша траса"
    )


def rcd_required_for_kinds(kinds: set[PointKind]) -> tuple[bool, str]:
    """Чи потрібен ПЗВ (пристрій захисного відключення)/дифавтомат для
    групи з такими типами точок, і коротке обґрунтування.

    Спрощене правило поширеної практики (PN-HD 60364-4-41, додатковий
    захист відключенням від ураження електричним струмом): кола розеток
    і кола вологих приміщень (бойлер) — обов'язково; стаціонарні потужні
    споживачі (плита) — обов'язково за сучасною практикою; кола лише
    освітлення без розеток — не завжди обов'язково, хоча дедалі частіше
    вимагається і для них.
    """
    if PointKind.SOCKET in kinds:
        return True, "коло містить розетку(и) — ПЗВ 30 мА обов'язковий"
    if PointKind.BOILER in kinds:
        return True, "коло живить бойлер (вологе приміщення) — ПЗВ 30 мА обов'язковий"
    if PointKind.STOVE in kinds:
        return True, "коло живить стаціонарний потужний споживач (плита) — ПЗВ/дифавтомат за сучасною практикою"
    return False, (
        "лише освітлення без розеток — за спрощеним правилом цього інструменту не "
        "обов'язково, але перевірте чинну редакцію норми: практика дедалі частіше "
        "вимагає ПЗВ і для кіл освітлення"
    )
